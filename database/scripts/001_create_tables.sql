-- USERS
CREATE TABLE USERS (
    USER_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY
                   CONSTRAINT PK_USERS PRIMARY KEY,
    USERNAME       VARCHAR2(50)  NOT NULL,
    EMAIL          VARCHAR2(100) NOT NULL,
    PASSWORD_HASH  VARCHAR2(256) NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL)
);

-- PROJECTS
CREATE TABLE PROJECTS (
    PROJECT_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT PK_PROJECTS PRIMARY KEY,
    USER_ID      NUMBER NOT NULL,
    NAME         VARCHAR2(200) NOT NULL,
    DESCRIPTION  VARCHAR2(2000),
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    IS_DELETED   NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_PROJECTS_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS (USER_ID)
);

-- TASKS
CREATE TABLE TASKS (
    TASK_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT PK_TASKS PRIMARY KEY,
    PROJECT_ID   NUMBER NOT NULL,
    TITLE        VARCHAR2(200) NOT NULL,
    DESCRIPTION  CLOB,
    PRIORITY     NUMBER DEFAULT 2 NOT NULL,
    STATUS       NUMBER DEFAULT 1 NOT NULL,
    DEADLINE     DATE,
    SORT_ORDER   NUMBER DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    IS_DELETED   NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_TASKS_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROJECTS (PROJECT_ID),
    CONSTRAINT CK_TASKS_PRIORITY CHECK (PRIORITY BETWEEN 1 AND 3),
    CONSTRAINT CK_TASKS_STATUS CHECK (STATUS BETWEEN 1 AND 3)
);

CREATE INDEX IDX_PROJECTS_USER ON PROJECTS (USER_ID, IS_DELETED);
CREATE INDEX IDX_TASKS_PROJECT ON TASKS (PROJECT_ID, STATUS, SORT_ORDER);

COMMENT ON TABLE USERS IS 'Tài khoản người dùng';
COMMENT ON TABLE PROJECTS IS 'Dự án cá nhân';
COMMENT ON TABLE TASKS IS 'Công việc trong dự án';
