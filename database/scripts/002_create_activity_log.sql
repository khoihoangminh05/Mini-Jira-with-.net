CREATE TABLE ACTIVITY_LOG (
    LOG_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT PK_ACTIVITY_LOG PRIMARY KEY,
    USER_ID      NUMBER NOT NULL,
    PROJECT_ID   NUMBER,
    TASK_ID      NUMBER,
    ACTION_TYPE  VARCHAR2(50)  NOT NULL,
    MESSAGE      VARCHAR2(500) NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ACTIVITY_USER FOREIGN KEY (USER_ID)
        REFERENCES USERS (USER_ID),
    CONSTRAINT FK_ACTIVITY_PROJECT FOREIGN KEY (PROJECT_ID)
        REFERENCES PROJECTS (PROJECT_ID),
    CONSTRAINT FK_ACTIVITY_TASK FOREIGN KEY (TASK_ID)
        REFERENCES TASKS (TASK_ID)
);

CREATE INDEX IDX_ACTIVITY_PROJECT ON ACTIVITY_LOG (PROJECT_ID, CREATED_AT DESC);
CREATE INDEX IDX_ACTIVITY_USER ON ACTIVITY_LOG (USER_ID, CREATED_AT DESC);

COMMENT ON TABLE ACTIVITY_LOG IS 'Nhat ky hoat dong task/project — Phase 9';
